"""
protector.tools.export_pubkey_blob — write a product's pubkey_blob.py.

Reads the ACTIVE keystore (the one the protector itself uses), unwraps it
with the vendor passphrase, and writes a fresh ``pubkey_blob.py`` for the
customer-side SDK of a new/protected product. This is the step-2 tool of
the integration guide (docs/INTEGRATION.md): the embedded public key must
be YOUR keystore's key, otherwise serials issued by the protector never
verify inside the product.

Usage (from the repository root):

    python protector/tools/export_pubkey_blob.py <path/to/your_app/protection> [keystore_path]

The keystore path defaults to %APPDATA%\\SecureCode\\Protector\\keystore.dat.
The passphrase is read from the terminal (never an argument, never logged).
"""

from __future__ import annotations

import base64
import getpass
import hashlib
import sys
from pathlib import Path

_REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(_REPO))

from protector.core.app_paths import KEYSTORE_PATH  # noqa: E402
from protector.core.crypto_engine import KeyStore  # noqa: E402

_TEMPLATE = '''"""
{name}.protection.pubkey_blob — GENERATED FILE. DO NOT EDIT BY HAND.

Generated by protector/tools/export_pubkey_blob.py. Contains the Ed25519
PUBLIC verification key (Base64) and its SHA-256 integrity digest.

The public key is not secret — its INTEGRITY is what matters: an attacker
who flips the embedded key to their own could make self-issued serials
verify. The digest stored here (and cross-checked in integrity.py) makes
naive patching of the key blob fail at startup.

This file has no runtime dependencies beyond the stdlib.
"""

from __future__ import annotations

import base64
import hashlib

#: Raw 32-byte Ed25519 public key (verification key) — never rotate without
#: regenerating every serial (they all embed signatures of this key).
PUBKEY_B64 = "{pub_b64}"

#: SHA-256 of the raw public key bytes (hex) — integrity cross-check target.
PUBKEY_DIGEST = "{digest}"

#: Key id (first 16 hex chars of SHA-256(pub)) — display only.
KEY_ID = "{key_id}"


def public_key_bytes() -> bytes:
    """Return the raw public key bytes (a fresh copy each call)."""
    return base64.b64decode(PUBKEY_B64.encode("ascii"))


def verify_own_digest() -> bool:
    """True when the embedded key matches the embedded digest.

    Patches to either constant independently (the common case in a hex
    editor) are detected here; integrity.py calls this at every startup.
    """
    return hashlib.sha256(public_key_bytes()).hexdigest() == PUBKEY_DIGEST
'''


def main() -> int:
    if len(sys.argv) < 2:
        print("usage: python protector/tools/export_pubkey_blob.py "
              "<path/to/your_app/protection> [keystore_path]")
        return 2

    target = Path(sys.argv[1]).resolve()
    if not target.is_dir():
        print(f"[error] protection directory not found: {target}")
        return 2
    keystore_path = Path(sys.argv[2]) if len(sys.argv) > 2 else KEYSTORE_PATH

    keystore = KeyStore(keystore_path)
    if not keystore.exists:
        print(f"[error] keystore not found: {keystore_path}")
        return 2
    passphrase = getpass.getpass("keystore passphrase: ")
    try:
        keystore.unlock(passphrase)
    except Exception as exc:  # noqa: BLE001 — CLI boundary
        print(f"[error] unlock failed: {exc}")
        return 1

    pub = keystore.public_key
    digest = hashlib.sha256(pub).hexdigest()
    product_dir = target.parent.name
    blob = _TEMPLATE.format(
        name=product_dir,
        pub_b64=base64.b64encode(pub).decode("ascii"),
        digest=digest,
        key_id=digest[:16],
    )
    out = target / "pubkey_blob.py"
    out.write_text(blob, encoding="utf-8")
    print(f"written: {out}")
    print(f"key id:  {digest[:16]}")
    print("next:    python protector/tools/build_strings_table.py && "
          "python protector/tools/make_integrity_manifest.py")
    keystore.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

"""
protector.tools.make_integrity_manifest — generate the SDK's Layer-4 manifest.

Writes ``integrity_manifest.py`` INSIDE a protection SDK package: a SHA-256
manifest of every SDK module (verified on each dev-mode launch and required
to be Nuitka-__compiled__ in frozen builds), the exact module list the frozen
build must contain, and the critical-material digest (pubkey || fingerprint
salt || payload schema version).

Two modes:
    * default (no arguments): the shipped demo layout — target_demo/protection
      with target_demo.protection import names. Byte-identical behavior to
      the original tool.
    * custom project: point the tool at a copied SDK (see docs/INTEGRATION.md):

        python protector/tools/make_integrity_manifest.py ^
            --sdk-dir path/to/your_app/protection ^
            --sdk-import-name protection ^
            [--shared-dir path/to/your_app/shared] [--shared-import-name shared]

The module list is DISCOVERED from the directory (every .py except the
manifest itself), so extra modules added to the SDK are covered automatically.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from datetime import datetime, timezone
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[2]

TEMPLATE = '''"""
{sdk_import_name}.integrity_manifest — GENERATED by
protector/tools/make_integrity_manifest.py. DO NOT EDIT BY HAND.

* SOURCE_MANIFEST: SHA-256 of each SDK module's source — verified on every
  dev-mode launch (any post-generation edit trips Layer 4).
* MODULE_NAMES: exact module set that must import (and be Nuitka __compiled__)
  in frozen builds.
* CRITICAL_DIGEST: SHA-256 of the critical verification material — cross-
  checked at runtime against integrity.critical_material().
"""

from __future__ import annotations

#: module name -> sha256 hex of its source file
SOURCE_MANIFEST: dict[str, str] = {{
{manifest_entries}
}}

#: every module the protection SDK consists of
MODULE_NAMES: tuple[str, ...] = (
{module_names}
)

#: sha256(pubkey || fingerprint salt || payload schema version)
CRITICAL_DIGEST: str = "{critical_digest}"

#: generation timestamp (UTC ISO) — for release traceability only
GENERATED_AT: str = "{generated_at}"
'''


def _discover_modules(sdk_dir: Path, sdk_import: str,
                     shared_dir: Path, shared_import: str) -> list[str]:
    """All SDK module import names, discovered from the directory layout.

    Convention (matches the shipped manifest): ``__init__.py`` files are
    listed as ``<pkg>.__init__``; everything else as ``<pkg>.<stem>``. The
    manifest module itself is excluded by definition (it cannot contain its
    own hash).
    """
    modules: list[str] = []

    def _add_package(directory: Path, import_name: str) -> None:
        for py in sorted(directory.glob("*.py")):
            if py.name == "__init__.py":
                modules.append(f"{import_name}.__init__")
            elif py.stem == "integrity_manifest":
                continue
            else:
                modules.append(f"{import_name}.{py.stem}")

    _add_package(shared_dir, shared_import)
    _add_package(sdk_dir, sdk_import)

    # The SDK's parent package __init__ (e.g. target_demo/__init__.py) —
    # included when the layout actually has one.
    if "." in sdk_import and (sdk_dir.parent / "__init__.py").is_file():
        parent = sdk_import.rsplit(".", 1)[0]
        modules.append(f"{parent}.__init__")
    return sorted(set(modules))


def _module_file(module: str, sdk_dir: Path, shared_dir: Path,
                 sdk_import: str, shared_import: str) -> Path:
    """Resolve an import name back to its source file (dev repo layout)."""
    sdk_parent = sdk_import.rsplit(".", 1)[0] if "." in sdk_import else None

    # Package __init__ files map to their package directory directly.
    if module == f"{sdk_import}.__init__":
        return sdk_dir / "__init__.py"
    if module == f"{shared_import}.__init__":
        return shared_dir / "__init__.py"
    if sdk_parent is not None and module == f"{sdk_parent}.__init__":
        init = sdk_dir.parent / "__init__.py"
        if init.is_file():
            return init
        raise FileNotFoundError(module)

    if module == shared_import or module.startswith(shared_import + "."):
        root, base = shared_dir, shared_import
    else:  # SDK submodule (or the SDK package itself)
        root, base = sdk_dir, sdk_import
    if module == base:
        return root / "__init__.py"
    rel = module[len(base) + 1:].replace(".", "/")
    direct = root / f"{rel}.py"
    if direct.is_file():
        return direct
    init = root / rel / "__init__.py"
    if init.is_file():
        return init
    raise FileNotFoundError(module)


def _critical_digest(sdk_dir: Path, shared_dir: Path,
                     sdk_import: str, shared_import: str) -> str:
    """SHA-256 over pubkey || fingerprint salt || payload schema version
    (must match integrity.critical_material())."""
    for path in (sdk_dir.parent, shared_dir.parent, _REPO_ROOT):
        if str(path) not in sys.path:
            sys.path.insert(0, str(path))
    pubkey_mod = __import__(f"{sdk_import}.pubkey_blob",
                            fromlist=["public_key_bytes"])
    schema_mod = __import__(f"{shared_import}.payload_schema",
                            fromlist=["FINGERPRINT_SALT", "PAYLOAD_VERSION"])
    material = (pubkey_mod.public_key_bytes() + schema_mod.FINGERPRINT_SALT
                + b"v%d" % schema_mod.PAYLOAD_VERSION)
    return hashlib.sha256(material).hexdigest()


def main() -> int:
    """Regenerate the integrity manifest (demo layout by default)."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--sdk-dir", type=Path,
                        default=_REPO_ROOT / "target_demo" / "protection",
                        help="the protection SDK package directory")
    parser.add_argument("--sdk-import-name", default="target_demo.protection",
                        help="dotted import name of the SDK package")
    parser.add_argument("--shared-dir", type=Path,
                        default=_REPO_ROOT / "shared",
                        help="the shared/ package directory")
    parser.add_argument("--shared-import-name", default="shared",
                        help="dotted import name of the shared package")
    args = parser.parse_args()

    sdk_dir: Path = args.sdk_dir.resolve()
    shared_dir: Path = args.shared_dir.resolve()
    if not sdk_dir.is_dir():
        print(f"[error] SDK directory not found: {sdk_dir}")
        return 2
    if not shared_dir.is_dir():
        print(f"[error] shared directory not found: {shared_dir}")
        return 2

    modules = _discover_modules(
        sdk_dir, args.sdk_import_name, shared_dir, args.shared_import_name)

    entries = []
    for module in modules:
        source = _module_file(module, sdk_dir, shared_dir,
                              args.sdk_import_name, args.shared_import_name)
        digest = hashlib.sha256(source.read_bytes()).hexdigest()
        entries.append(f'    "{module}": "{digest}",')
    module_names = "\n".join(f'    "{module}",' for module in modules)
    content = TEMPLATE.format(
        sdk_import_name=args.sdk_import_name,
        manifest_entries="\n".join(entries),
        module_names=module_names,
        critical_digest=_critical_digest(
            sdk_dir, shared_dir,
            args.sdk_import_name, args.shared_import_name),
        generated_at=datetime.now(timezone.utc).isoformat(timespec="seconds"),
    )
    output = sdk_dir / "integrity_manifest.py"
    output.write_text(content, encoding="utf-8")
    print(f"[ok] manifest written -> {output} ({len(modules)} modules)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

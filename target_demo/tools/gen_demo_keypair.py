"""
protector.tools.gen_demo_keypair — DEVELOPMENT-TIME tool (never shipped).

Generates a fresh Ed25519 demo keypair so the repository ships with a
matching, out-of-the-box pair:

    1. target_demo/protection/pubkey_blob.py
         The PUBLIC key (raw, Base64) + its SHA-256 integrity digest.
         This file is compiled into the distributed EXE (Nuitka) — the
         private key is NOT part of it.
    2. demo-assets/demo_keypair.sec
         The PRIVATE key, passphrase-wrapped with AES-256-GCM
         (passphrase: demo-demo-demo) using the exact same container format
         as protector's keystore exports. Import it into the protector via
         Settings -> Keystore -> "Import encrypted key export" to issue
         serials that the demo EXE accepts.

Run:
    python target_demo/tools/gen_demo_keypair.py
    (or:  python -m target_demo.tools.gen_demo_keypair)

WARNING: the demo private key is intentionally SHIPPED for convenience of the
sample project. Never ship it with a real commercial product — generate a
real keypair inside the protector and keep the export offline.
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

# Make repo root importable when executed as a plain script.
_REPO_ROOT = Path(__file__).resolve().parents[2]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from protector.core.crypto_engine import (  # noqa: E402
    KEYEXPORT_FORMAT,
    b64,
    generate_keypair,
    public_key_id,
    wrap_container,
)

DEMO_PASSPHRASE = "demo-demo-demo"  # documented in README (demo only!)
PUBKEY_FILE = _REPO_ROOT / "target_demo" / "protection" / "pubkey_blob.py"
DEMO_SEC_FILE = _REPO_ROOT / "demo-assets" / "demo_keypair.sec"

PUBKEY_TEMPLATE = '''"""
target_demo.protection.pubkey_blob — GENERATED FILE. DO NOT EDIT BY HAND.

Generated by target_demo/tools/gen_demo_keypair.py. Contains the Ed25519
PUBLIC verification key (Base64) and its SHA-256 integrity digest.

The public key is not secret — its INTEGRITY is what matters: an attacker who
flips the embedded key to their own could make self-issued serials verify.
The digest stored here (and cross-checked in integrity.py) makes naive
patching of the key blob fail at startup.

This file has no runtime dependencies beyond the stdlib.
"""

from __future__ import annotations

import base64
import hashlib

#: Raw 32-byte Ed25519 public key (verification key) — never rotate without
#: regenerating every serial (they all embed signatures of this key).
PUBKEY_B64 = "{pub_b64}"

#: SHA-256 of the raw public key bytes (hex) — integrity cross-check target.
PUBKEY_DIGEST = "{digest}"

#: Key id (first 16 hex chars of SHA-256(pub)) — display only.
KEY_ID = "{key_id}"


def public_key_bytes() -> bytes:
    """Return the raw public key bytes (a fresh copy each call)."""
    return base64.b64decode(PUBKEY_B64.encode("ascii"))


def verify_own_digest() -> bool:
    """True when the embedded key matches the embedded digest.

    Patches to either constant independently (the common case in a hex
    editor) are detected here; integrity.py calls this at every startup.
    """
    return hashlib.sha256(public_key_bytes()).hexdigest() == PUBKEY_DIGEST
'''


def main() -> int:
    """Generate the demo keypair, write both output files."""
    seed, pub = generate_keypair()
    digest = hashlib.sha256(pub).hexdigest()
    key_id = public_key_id(pub)

    PUBKEY_FILE.parent.mkdir(parents=True, exist_ok=True)
    PUBKEY_FILE.write_text(
        PUBKEY_TEMPLATE.format(
            pub_b64=b64(pub),
            digest=digest,
            key_id=key_id,
        ),
        encoding="utf-8",
    )

    DEMO_SEC_FILE.parent.mkdir(parents=True, exist_ok=True)
    export = wrap_container(DEMO_PASSPHRASE, {
        "format": KEYEXPORT_FORMAT,
        "version": 1,
        "private_key": b64(seed),
        "public_key": b64(pub),
        "created": 0,
        "key_id": key_id,
        "label": "SecureCode demo keypair",
    })
    DEMO_SEC_FILE.write_bytes(export)

    print(f"[ok] public key  -> {PUBKEY_FILE}")
    print(f"[ok] private key -> {DEMO_SEC_FILE}  (passphrase: {DEMO_PASSPHRASE})")
    print(f"[ok] key id: {key_id}")
    print("[!] The old demo keypair (if any) is now INVALID — regenerate serials.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

"""
target_demo.protection.integrity — Layer 4: self-integrity (anti-tamper).

Three complementary checks, executed on every launch (frozen mode) or on
demand (dev mode):

    1. verify_public_key()     — SHA-256 of the embedded Ed25519 public key
       vs. the digest stored beside it (pubkey_blob.py). An attacker who
       patches the key blob to their own key (the classic "swap the verify
       key" attack on offline licensing) fails here — both constants are
       only visible in the binary as encrypted/scattered literals.

    2. verify_modules()        — the import-integrity manifest. At build
       time (protector/tools/make_integrity_manifest.py) every SDK module's
       SHA-256 is recorded. At runtime:
         * dev mode: module FILES are re-hashed and compared (catches any
           edit to the SDK after the manifest was generated).
         * frozen mode (Nuitka): files do not exist; instead every expected
           module must import AND carry Nuitka's __compiled__ marker —
           together with the public-key digest this verifies that the
           running module set is exactly the compiled one (bytecode-level
           hashing is unnecessary in frozen mode: Nuitka modules ARE native
           code, no .pyc exists that could be swapped).

    3. verify_critical_constants() — SHA-256 over the critical verification
       material (public key + fingerprint salt + payload schema version)
       compared against a digest in the manifest. Patching any of the
       verification constants WITHOUT also finding and patching the
       manifest digest makes startup fail.

On failure the callers (ProtectionRuntime.bootstrap / LicenseClient) exit
silently or surface a generic "damaged" error — never "integrity failed"
(anti-feedback: the attacker should not learn WHICH check tripped).

Honest scope note (docs/SECURITY.md): a native binary can ultimately be
patched by a determined expert with a disassembler; these checks raise the
cost by requiring MULTIPLE, mutually-cross-checking edits done correctly
on compiled code. True self-hashing of the whole PE image is listed there
as a documented future enhancement (external packer step).
"""

from __future__ import annotations

import hashlib
import importlib
import logging
import sys
from pathlib import Path

from shared.payload_schema import FINGERPRINT_SALT, PAYLOAD_VERSION

log = logging.getLogger("protection.integrity")

from .pubkey_blob import public_key_bytes  # noqa: E402

try:  # manifest is generated by tools/make_integrity_manifest.py
    from .integrity_manifest import (
        CRITICAL_DIGEST,
        MODULE_NAMES,
        SOURCE_MANIFEST,
    )
    _HAS_MANIFEST = True
except ImportError:  # pragma: no cover — manifest missing = dev checkout
    log.warning("integrity manifest missing — module self-checks degraded")
    CRITICAL_DIGEST = ""
    MODULE_NAMES: tuple[str, ...] = ()
    SOURCE_MANIFEST: dict[str, str] = {}
    _HAS_MANIFEST = False


# ---------------------------------------------------------------------------
# Individual checks
# ---------------------------------------------------------------------------
def verify_public_key() -> bool:
    """Embedded public key matches its embedded digest (pubkey swap attack)."""
    from .pubkey_blob import verify_own_digest

    return verify_own_digest()


def critical_material() -> bytes:
    """The exact byte sequence the critical-constants digest is taken over.

    Order: pubkey || fingerprint salt || payload schema version. Changing
    ANY verification-relevant constant changes this hash.
    """
    return public_key_bytes() + FINGERPRINT_SALT + b"v%d" % PAYLOAD_VERSION


def verify_critical_constants() -> bool:
    """Critical verification material matches the manifest digest."""
    if not _HAS_MANIFEST:
        return True  # dev checkout without manifest; documented degradation
    actual = hashlib.sha256(critical_material()).hexdigest()
    return actual == CRITICAL_DIGEST


def _frozen_mode() -> bool:
    """True when running as a Nuitka-compiled binary (or any frozen build)."""
    return getattr(sys, "frozen", False) or "__compiled__" in globals()


def _import_name(module_name: str) -> str:
    """Manifest name -> importable name.

    The manifest lists package ``__init__`` modules as ``pkg.__init__``
    (a file-level name), but the import system knows that module as the
    package itself, ``pkg``. CPython tolerates the synthetic submodule
    spelling; Nuitka's compiled import system does NOT — it fails to
    resolve ``pkg.__init__`` in frozen builds. Normalize before importing.
    """
    if module_name.endswith(".__init__"):
        return module_name[: -len(".__init__")]
    return module_name


def verify_modules() -> tuple[bool, list[str]]:
    """Import-integrity of the SDK's own modules (see module docstring).

    Returns:
        (ok, problems) — problems never contain secrets, only module names.
    """
    if not _HAS_MANIFEST:
        return True, []

    problems: list[str] = []

    if _frozen_mode():
        # Native build: every module must import and be Nuitka-compiled.
        for module_name in MODULE_NAMES:
            try:
                mod = importlib.import_module(_import_name(module_name))
                if not hasattr(mod, "__compiled__"):
                    problems.append(module_name)
            except Exception:
                problems.append(module_name)
    else:
        # Source build: compare file content hashes against the manifest.
        # Modules resolve through the IMPORT system (layout-agnostic: works
        # for the shipped demo layout AND for SDKs copied into arbitrary
        # projects — see docs/INTEGRATION.md), never through a guessed
        # directory depth.
        for module_name, expected in SOURCE_MANIFEST.items():
            try:
                mod = importlib.import_module(_import_name(module_name))
                source = Path(getattr(mod, "__file__", "")).resolve()
                match = source.is_file() and \
                    hashlib.sha256(source.read_bytes()).hexdigest() == expected
            except Exception:  # noqa: BLE001 — any import failure = problem
                match = False
            if not match:
                problems.append(module_name)

    return (not problems), problems


def run_integrity_checks() -> tuple[bool, list[str]]:
    """Run ALL Layer 4 checks. Returns (ok, problems) — never raises."""
    problems: list[str] = []
    if not verify_public_key():
        problems.append("pk")
    if not verify_critical_constants():
        problems.append("cc")
    ok_mods, mod_problems = verify_modules()
    problems.extend(mod_problems)
    if problems:
        # Only module names / short codes in the log — nothing an attacker
        # can use as a roadmap; enough for the vendor to diagnose reports.
        log.error("integrity self-check failed: %d problem(s): %s",
                  len(problems), ", ".join(problems))
    return (not problems), problems


__all__ = [
    "critical_material",
    "run_integrity_checks",
    "verify_critical_constants",
    "verify_modules",
    "verify_public_key",
]
